/* [mem_doc kto="policy|consent|cookies"]текст ссылки[/mem_doc] — ссылка на другой документ */
add_shortcode('mem_doc', function ($atts, $content = '') {
    $a = shortcode_atts(['kto' => 'policy'], $atts, 'mem_doc');
    $k = array_key_exists($a['kto'], mem_legal_docs()) ? $a['kto'] : 'policy';
    return mem_legal_link($k, trim(wp_strip_all_tags((string) $content)));
});

function mem_legal_template($key) {
    $h = fn($t) => "<!-- wp:heading -->\n<h2 class=\"wp-block-heading\">$t</h2>\n<!-- /wp:heading -->\n\n";
    $p = fn($t) => "<!-- wp:paragraph -->\n<p>$t</p>\n<!-- /wp:paragraph -->\n\n";
    $ul = function (array $items) {
        $li = '';
        foreach ($items as $i) $li .= "<!-- wp:list-item -->\n<li>$i</li>\n<!-- /wp:list-item -->\n";
        return "<!-- wp:list -->\n<ul class=\"wp-block-list\">$li</ul>\n<!-- /wp:list -->\n\n";
    };
    $date = wp_date('d.m.Y');
    $op = '[mem_operator]';

    if ($key === 'policy') {
        return $p("Редакция от $date")
        . $h('1. Общие положения')
        . $p("Настоящая Политика определяет порядок обработки и защиты персональных данных посетителей сайта [mem_operator chto=\"сайт\"] (далее — Сайт). Оператор персональных данных — $op (далее — Оператор). Политика разработана в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных».")
        . $p('Используя Сайт и оставляя на нём свои данные, посетитель подтверждает, что ознакомлен с Политикой. Согласие на обработку данных, оставленных в форме, даётся отдельно — [mem_doc kto="consent"]Согласие на обработку персональных данных[/mem_doc].')
        . $h('2. Какие данные мы обрабатываем')
        . $ul([
            'имя (как к вам обращаться) и номер телефона — когда вы оставляете заявку «Перезвоните мне»;',
            'данные, которые вы сами сообщаете при звонке или переписке в мессенджерах;',
            'технические данные: cookie, IP-адрес, сведения о браузере и устройстве, страницы, которые вы смотрели, — их собирает сервис «Яндекс Метрика» (подробнее — [mem_doc kto="cookies"]Политика использования cookie[/mem_doc]).',
        ])
        . $h('3. Зачем мы их обрабатываем')
        . $ul([
            'чтобы перезвонить вам и проконсультировать по ритуальным услугам и товарам;',
            'чтобы заключить и исполнить договор на оказание услуг;',
            'чтобы улучшать работу Сайта и понимать, какие страницы полезны посетителям (обезличенная статистика).',
        ])
        . $h('4. Основания и сроки')
        . $p('Данные обрабатываются с вашего согласия, а также когда это нужно для заключения и исполнения договора. Данные из заявок хранятся не дольше, чем нужно для этих целей, но не более 3 лет с последнего обращения, затем удаляются. Вы можете в любой момент отозвать согласие (раздел 7).')
        . $h('5. Как мы обращаемся с данными')
        . $p('Оператор собирает, записывает, хранит, уточняет, использует и удаляет данные; не продаёт их и не передаёт третьим лицам, кроме случаев, предусмотренных законом. Обезличенные статистические данные обрабатывает ООО «Яндекс» (сервис «Яндекс Метрика»). Данные хранятся на серверах, расположенных в России. Оператор принимает правовые, организационные и технические меры для защиты данных от неправомерного доступа, изменения, распространения и уничтожения.')
        . $h('6. Cookie')
        . $p('Сайт использует cookie. Какие и зачем — в [mem_doc kto="cookies"]Политике использования cookie[/mem_doc]. Отключить cookie можно в настройках браузера.')
        . $h('7. Ваши права')
        . $p('Вы вправе узнать, какие ваши данные мы обрабатываем, потребовать их уточнения, блокирования или удаления, отозвать согласие на обработку, обжаловать действия Оператора в Роскомнадзоре или суде. Для этого напишите на [mem_operator chto="почта"] или позвоните [mem_operator chto="телефон"]. Мы ответим в течение 10 рабочих дней.')
        . $h('8. Контакты Оператора')
        . $p("$op<br>Адрес: [mem_operator chto=\"адрес\"]<br>Эл. почта: [mem_operator chto=\"почта\"]<br>Телефон: [mem_operator chto=\"телефон\"]")
        . $p('Оператор может изменять Политику; новая редакция действует с момента публикации на этой странице.');
    }

    if ($key === 'consent') {
        return $p("Редакция от $date")
        . $p("Отмечая галочку «Согласен» в форме на сайте [mem_operator chto=\"сайт\"] и отправляя заявку, я свободно, своей волей и в своём интересе даю $op (далее — Оператор) согласие на обработку моих персональных данных на следующих условиях.")
        . $h('Какие данные')
        . $p('Имя (как ко мне обращаться), номер телефона, а также сведения, которые я сообщу Оператору при разговоре или в переписке.')
        . $h('Цель')
        . $p('Связаться со мной по моей заявке, проконсультировать по ритуальным услугам и товарам, заключить и исполнить договор.')
        . $h('Действия с данными')
        . $p('Сбор, запись, систематизация, накопление, хранение, уточнение (обновление, изменение), извлечение, использование, блокирование, удаление и уничтожение — с использованием средств автоматизации и без них. Передача данных третьим лицам не допускается, кроме случаев, предусмотренных законом.')
        . $h('Срок и отзыв')
        . $p('Согласие действует 3 года со дня отправки заявки или до его отзыва. Отозвать согласие можно, написав на [mem_operator chto="почта"] или позвонив [mem_operator chto="телефон"]; после отзыва Оператор прекращает обработку и удаляет данные в течение 30 дней, если иное не требуется по закону.')
        . $p('Подробнее о том, как Оператор обрабатывает и защищает данные, — в [mem_doc kto="policy"]Политике обработки персональных данных[/mem_doc].');
    }

    if ($key === 'cookies') {
        return $p("Редакция от $date")
        . $p("Сайт [mem_operator chto=\"сайт\"] использует cookie — небольшие файлы, которые браузер сохраняет на вашем устройстве. Они помогают сайту работать и показывают, как посетители им пользуются. Владелец сайта — $op.")
        . $h('Какие cookie мы используем')
        . $ul([
            '<strong>Необходимые</strong> — запоминают ваш выбор на сайте (например, ответ в плашке о cookie). Без них сайт работает неправильно.',
            '<strong>Аналитические</strong> — сервис «Яндекс Метрика» (ООО «Яндекс») собирает обезличенные данные: какие страницы открывают, сколько на них проводят времени, с какого устройства и откуда пришли. По ним мы улучшаем сайт. Мы не используем эти данные, чтобы установить вашу личность.',
            '<strong>Сторонних сервисов</strong> — встроенные карты и отзывы Яндекса могут ставить свои cookie по правилам Яндекса.',
        ])
        . $h('Как отказаться')
        . $p('Отключить или удалить cookie можно в настройках браузера — сайт продолжит работать, но некоторые функции могут работать хуже. Отказаться от «Яндекс Метрики» можно и с помощью <a href="https://yandex.ru/support/metrica/general/opt-out.html" target="_blank" rel="noopener">блокировщика Яндекса</a>.')
        . $p('Как мы обрабатываем персональные данные — в [mem_doc kto="policy"]Политике обработки персональных данных[/mem_doc]. Вопросы — на [mem_operator chto="почта"].');
    }
    return '';
}
